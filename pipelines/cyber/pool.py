def market_of(ticker: str) -> str:
    """Key of ``pipelines.valuation.config.MARKET_FUNDAMENTALS`` for a Yahoo symbol; no suffix means a US listing."""
    for suffix, market in _SUFFIX_MARKET.items():
        if ticker.endswith(suffix):
            return market
    return "us"


