@dataclass
class Obs:
    company: str
    metric: str
    period: str          # as written
    cal: str | None      # calendar label, or None when it cannot be aligned
    gran: str
    value: float
    qualifier: str
    unit: str
    kind: str
    chartable: bool
    stale: bool
    reasons: list[str]   # why this observation cannot enter a USD period-total pool; empty = eligible


def _obs(r: dict) -> Obs:
    cal, align = calendar_period(str(r["period"]), str(r["as_of_date"]))
    reasons: list[str] = []
    if r.get("chartable") is not True or r.get("metric_kind") in NEVER_CHARTED_KINDS:
        reasons.append(f"curated row not chartable (tag {r.get('tag')}, {r.get('metric_kind')})")
    if r.get("unit") != USD:
        reasons.append(f"reported in {r.get('unit')}; pools are in USD and share.py does not convert currencies")
    if r.get("metric_kind") == "stated_run_rate":
        reasons.append("annualised run rate; never mixed with period totals")
    if align and r.get("metric_kind") != "stated_run_rate":
        reasons.append(align)
    return Obs(company=r["company"], metric=r["metric"], period=str(r["period"]), cal=cal,
               gran=granularity(str(r["period"])), value=float(r["value"]), qualifier=r["qualifier"],
               unit=str(r.get("unit")), kind=str(r.get("metric_kind")), chartable=r.get("chartable") is True,
               stale=bool(r.get("stale")), reasons=reasons)


