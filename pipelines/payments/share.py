"""Share by lens: four separately labelled measurements that are never added together.

PLAN §3 M3, EXECUTION W2c, section H "Share rules" of docs/EVALUATION_PLAN.md. "Share" in payments depends
entirely on what is counted, so this module never produces one market-share number. It produces four lenses,
each with its own denominator, unit and caveats, in one long table, plus a concentration (HHI) table for the
lenses where a closed pool exists:

``disclosed_pool``         each listed company's payment volume as a share of the sum over the companies in the
                           same layer that disclose a comparable volume for the same calendar period. Labelled
                           "share of disclosed pool", never market share. HHI is computed inside the pool only.
``official_denominator``   a company's volume over an official total, only when scope (US vs global), measure
                           and period match. BNPL uses the Fed FEDS Note table, whose numerators and total come
                           from the same table. Every mismatch is a *refusal row*: no number, a reason instead.
``web_coverage``           HTTP Archive origins carrying a technology, over all origins in the crawl slice
                           (webtech.py output). Always "coverage", never share of payments.
``developer_downloads``    share of npm downloads among the pinned SDK set (devstats.py output). Downloads are
                           not developers and not dollars.

Rules this module enforces (each has a test)
--------------------------------------------
* **Chartable rows only.** A curated row reaches a number in this table only when ``chartable`` is true (tag V or
  C; ``reported_talks`` / ``third_party_estimate`` are never chartable, reference.py guarantees it). A pool member
  whose row is not chartable appears as an ``excluded`` row with the reason and no value. Private rows that are
  not chartable are dropped entirely: they belong in the separate "reported, unconfirmed" table (ledger.py).
* **Layers are never summed.** A pool belongs to one layer; the HHI table has one row per (lens, pool, period)
  and a pool total is the sum of that pool's members only. Lenses are never combined: web coverage overlaps
  (one origin carries several technologies) and downloads are not volume.
* **One period, one definition.** Fiscal periods are aligned to calendar periods by their end date
  (``calendar_period``); a fiscal quarter that does not end in March/June/September/December is refused, not
  shifted. Annualised run rates (``stated_run_rate`` rows) never enter a pool of period totals. Half-year figures
  enter only a calendar-year pool, and only as H1 + H2.
* **One currency.** Pools are in USD. share.py does not convert currencies: a converted volume would carry an
  exchange-rate choice into every other member's share. A member reporting in EUR or AUD is excluded with that
  reason (Adyen, Zip), so the exclusion is visible on the page instead of buried in a rate.
* **Private companies are markers, never pool members.** Decision for Stripe (and Checkout.com, Ramp, Mercury,
  Airwallex): a stated private volume is shown beside the pool as a ``marker`` row with its own qualifier, and
  never enters the pool sum, even where the period matches. Three reasons: (1) it is a company statement, not a
  filing, and its definition is not broken down ("total volume generated by businesses running on Stripe");
  (2) private figures are annual or annualised, while pools are mostly quarterly; (3) it overlaps public pool
  members: Shopify Payments is processed by Stripe, so Stripe's total already contains Shopify's gross payments
  volume, and adding both would count the same dollar twice. Q1 is the exception the registration itself makes:
  it needs Stripe's share of a named five-company set, which ``q1_volume_share`` computes as an interval.

Qualifier propagation (``=`` exact, ``>`` lower bound, ``<`` upper bound, ``~`` approximate)
---------------------------------------------------------------------------------------------
``q_sum``    a sum of exact values is exact; ``~`` anywhere makes it ``~``; ``=`` with ``>`` is ``>`` (a lower
             bound plus exact values is a lower bound); ``=`` with ``<`` is ``<``; ``>`` with ``<`` is ``~``: the
             two bounds point in opposite directions, so the result is neither bound. It is not refused, because
             the point value is still the best reading, but it is never presented as a bound.
``q_ratio``  numerator / denominator, positive values: the denominator's direction flips (a lower-bound
             denominator gives an upper-bound ratio), then the two combine as in ``q_sum``.
``q_share``  x / (x + rest) rises with x and falls with rest, so it is ``q_ratio`` of x against the rest:
             a member with ``>`` volume gets a ``>`` share, and every other member a ``<`` share.
``q_hhi``    a sum of squared shares moves in both directions when one input is a bound, so any non-exact share
             makes the HHI ``~``.

Usage::

    uv run python -m pipelines.payments.share            # build and write data/marts/payments/share_*.parquet
    uv run python -m pipelines.payments.share --dry-run  # build, validate, print checks, write nothing
"""

