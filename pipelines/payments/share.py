def _value_xor_reason(data) -> pl.LazyFrame:
    return data.lazyframe.select(pl.col("value").is_null() == pl.col("refusal_reason").is_not_null())


def _qualifier_with_value(data) -> pl.LazyFrame:
    return data.lazyframe.select(pl.col("value").is_null() == pl.col("qualifier").is_null())


def _share_in_unit_range(data) -> pl.LazyFrame:
    is_share = pl.col("unit").is_in(SHARE_UNITS)
    return data.lazyframe.select(~is_share | pl.col("value").is_null()
                                 | ((pl.col("value") >= 0) & (pl.col("value") <= 1)))


def _numbers_only_for_members(data) -> pl.LazyFrame:
    return data.lazyframe.select(~pl.col("role").is_in(["excluded", "refused"]) | pl.col("value").is_null())


