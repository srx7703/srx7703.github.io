# --- qualifier algebra -----------------------------------------------------------------------


def flip(q: str) -> str:
    """Direction of a quantity that enters with a negative sign (a denominator, the rest of a pool)."""
    return {">": "<", "<": ">"}.get(q, q)


def q_sum(qs: Iterable[str]) -> str:
    s = set(qs)
    bad = s - set(QUALIFIERS)
    if bad:
        raise ValueError(f"unknown qualifier(s) {sorted(bad)}")
    if "~" in s or {">", "<"} <= s:
        return "~"
    if ">" in s:
        return ">"
    if "<" in s:
        return "<"
    return "="


def q_ratio(q_num: str, q_den: str) -> str:
    return q_sum([q_num, flip(q_den)])


def q_share(q_self: str, q_rest: str) -> str:
    return q_ratio(q_self, q_rest)


def q_hhi(share_qs: Iterable[str]) -> str:
    qs = list(share_qs)
    return "=" if all(q == "=" for q in qs) else "~"


def bounds(value: float, q: str) -> tuple[float, float]:
    """The interval a qualified figure stands for."""
    if q == "=":
        return value, value
    if q == ">":
        return value, math.inf
    if q == "<":
        return 0.0, value
    if q == "~":
        return value * (1 - APPROX_REL_TOL), value * (1 + APPROX_REL_TOL)
    raise ValueError(f"unknown qualifier {q!r}")


# --- calendar alignment ----------------------------------------------------------------------

_MONTH = ["", "January", "February", "March", "April", "May", "June", "July", "August", "September",
          "October", "November", "December"]


def granularity(period: str) -> str:
    if re.search(r"Q[1-4]$", period):
        return "quarter"
    if re.search(r"(^H[12]-\d{4}$)|(-H[12]$)", period):
        return "half"
    if re.fullmatch(r"FY\d{4}", period):
        return "year"
    return "other"  # a month ('2026-03') or a bare year label: point-in-time or run-rate statements


def calendar_period(period: str, as_of_date: str) -> tuple[str | None, str | None]:
    """(calendar label, refusal reason). The curated ``as_of_date`` is the period end, so a fiscal period is
    placed by where it ends: Affirm FY2026-Q4 (ends 2026-06-30) is 2026-Q2; Navan FY2027-Q2 (ends July) is no
    calendar quarter and is refused rather than shifted by a month."""
    g = granularity(period)
    end = date.fromisoformat(as_of_date[:10])
    if g == "quarter":
        if end.month % 3:
            return None, f"fiscal quarter ends in {_MONTH[end.month]}, not a calendar quarter"
        return f"{end.year}-Q{end.month // 3}", None
    if g == "half":
        if end.month not in (6, 12):
            return None, f"fiscal half ends in {_MONTH[end.month]}, not a calendar half"
        return f"H{end.month // 6}-{end.year}", None
    if g == "year":
        if end.month != 12:
            return None, f"fiscal year ends in {_MONTH[end.month]}, not a calendar year"
        return f"FY{end.year}", None
    return None, "not a period total (point-in-time or annualised statement)"


def period_sort_key(label: str | None) -> tuple[int, int]:
    """Calendar order; a year sorts after its fourth quarter."""
    if not label:
        return (0, 0)
    m = re.fullmatch(r"(\d{4})-Q([1-4])", label)
    if m:
        return int(m.group(1)), int(m.group(2)) * 2
    m = re.fullmatch(r"FY(\d{4})", label)
    if m:
        return int(m.group(1)), 9
    m = re.fullmatch(r"H([12])-(\d{4})", label)
    if m:
        return int(m.group(2)), int(m.group(1)) * 4 + 1
    return (0, 0)


